# -*- coding: utf-8 -*-
"""Синтетический демо-корпус: чтобы продукт проверялся из коробки.

Зачем. Все измерения в README сделаны на корпусах, которые нельзя публиковать
(личная переписка, чужие диалоги). Человек, который клонирует репозиторий, должен
иметь возможность за пять минут получить работающий архив и свои числа — иначе
он просто верит мне на слово.

Корпус намеренно СИНТЕТИЧЕСКИЙ: это не «похоже на настоящую переписку», а
сгенерированные записи рабочего проекта. Этого достаточно, чтобы убедиться, что
пайплайн жив: собирается архив, ищется, переносится. Свои числа каждый строит на
своём корпусе через make_bench.py.

    python make_demo_corpus.py --out demo_corpus.txt --n 1200
"""
import argparse, json, os, random

# Каркас: выдуманный проект с узнаваемой структурой — чтобы факты были
# привязаны к контексту и поиск был осмысленным, а не на случайных словах.
MODULES = [
    ('payment-gateway', ['идемпотентность ключей', 'повторная отправка чека',
                         'таймаут эквайера', 'возврат при частичной оплате']),
    ('user-profile', ['merge ссылок', 'нормализация телефона', 'soft delete',
                      'импорт из старой CRM']),
    ('search-index', ['переиндексация ночью', 'синонимы для брендов',
                      'вес поля title', 'падение на длинных запросах']),
    ('notification-bus', ['дедуп писем', 'ordering сообщений', 'dead-letter очередь',
                          'троттлинг провайдера']),
    ('auth-service', ['ротация refresh токена', 'утечка в логах', 'rate limit на логин',
                      'пересессия при смене пароля']),
    ('reporting', ['материализация витрин', 'кэш агрегатов', 'срез по часовым поясам',
                   'расхождение с биллингом']),
    ('mobile-client', ['кэш образов', 'офлайн-режим', 'падение на старых Android',
                       'размер бандла']),
    ('infra', ['autoscaling по очереди', 'сетевая политика', 'секреты в vault',
               'стоимость логов']),
]
EVENTS = [
    'Понесли фикс: {t}. Причина — {cause}. Воспроизвелось {n} из {m} попыток на {env}.',
    'Решение по {t}: делаем через {approach}, потому что {because}. Оценили в {d} дня.',
    'Обсуждали {t}. Риск: {risk}. Решили мониторить метрику «{metric}».',
    'Инцидент: {t} затронул {pct}% пользователей. Откатили релиз {ver}, причину ищем в {place}.',
    'Заметка. {t} — актуально для {env}. Договорились: {approach}. Ответственный {who}.',
    'Техдолг по {t}: {cause}. Если не починить, {risk}. Оценка — {d} дня.',
    'Ревью: {t} сделано через {approach}. Замечание — {risk}. Принято после правки.',
    'Метрика «{metric}» просела на {pct}% после включения {t}. Откат на {ver}, разбор во вторник.',
]
CAUSES = ['гонка потоков', 'устаревший драйвер', 'неверный часовой пояс',
          'забыли индекс в БД', 'сериализация теряет поле', 'кэш не инвалидируется',
          'ретраи без backoff', 'не тот порядок миграций']
APPROACHES = ['отдельную таблицу', 'очередь с дедупликацией', 'фича-флаг',
              'материализованное представление', 'внешний воркер', 'кеш на редисе',
              'двухфазную запись', 'ручной разбор в саппорте']
BECAUSES = ['дешевле в поддержке', 'так быстрее на пике', 'это уже проверено в бою',
            'иначе разъедется с биллингом', 'требует меньше миграций',
            'так проще откатить']
RISKS = ['можно потерять данные', 'растёт задержка', 'усложняется откат',
         'понадобится ручная сверка', 'упрёмся в лимит провайдера',
         'метрика станет нестабильной']
METRICS = ['p95 latency', 'доля ошибок', 'время индексации', 'размер очереди',
           'конверсия в оплату', 'время ответа API']
ENVS = ['проде', 'стейдже', 'тестовом контуре']
WHO = ['Ирина', 'Марк', 'Олег', 'Даша', 'Тимур']
PLACES = ['логах воркера', 'трейсах API', 'метриках очереди', 'дампе БД']
CODES = ['VG', 'KR', 'ZT', 'NR', 'PM', 'TX', 'ОР', 'ЛД', 'СБ', 'АК']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='demo_corpus.txt')
    ap.add_argument('--n', type=int, default=1200, help='сколько записей')
    ap.add_argument('--seed', type=int, default=20260912)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    lines, day = [], 1
    for i in range(args.n):
        mod, topics = MODULES[i % len(MODULES)]
        topic = rng.choice(topics)
        tpl = rng.choice(EVENTS)
        day += rng.choice([0, 0, 1, 2])
        # ЯКОРЬ. Корпус собирается из шаблонов, поэтому без него фрагменты почти
        # неотличимы: вопрос «какой инцидент затронул 6%?» одинаково подходит к
        # десятку записей, и метрика незаслуженно падает. Уникальный код дает
        # адресуемость — ровно то, зачем вообще нужен поиск.
        ticket = f'{rng.choice(CODES)}-{rng.randint(100, 9999)}'
        # АБЗАЦ, а не строка. Запись в 160 символов давала бы 5 штук в одном
        # 800-символьном окне: вопрос модели относился к одной, а «редкие термины»
        # метрики выдирались из соседних — метрика мерила не то. Один абзац ≈ одно
        # окно ⇒ вопрос и метрика относятся к одному и тому же куску текста.
        # Тикет называем ОДИН раз. Если повторять его в каждом предложении,
        # частота слова по корпусу взлетает, и он выпадает из «редких терминов» —
        # то есть ровно тот якорь, по которому фрагмент и находится, метрика
        # перестанет видеть. Дальше — местоимения.
        t_short = rng.choice(['этот тикет', 'задача', 'правка', f'{mod}: {topic}'])
        parts = []
        for j in range(rng.randint(4, 6)):
            tpl = rng.choice(EVENTS)
            parts.append(tpl.format(
                t=(f'{mod}: {topic} (тикет {ticket})' if j == 0 else t_short),
                cause=rng.choice(CAUSES), n=rng.randint(2, 9), m=rng.randint(10, 20),
                env=rng.choice(ENVS), approach=rng.choice(APPROACHES),
                because=rng.choice(BECAUSES), risk=rng.choice(RISKS),
                metric=rng.choice(METRICS), pct=rng.randint(3, 40),
                ver=f'2026.{rng.randint(1, 12):02d}.{rng.randint(1, 28):02d}',
                place=rng.choice(PLACES), d=rng.randint(1, 14),
                who=rng.choice(WHO)))
        rec = ' '.join(parts)
        stamp = f'[2026-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d} #{i:04d}]'
        lines.append(f'{stamp} {rec}')

    text = '\n'.join(lines)
    open(args.out, 'w', encoding='utf-8').write(text)
    print(f'записей {len(lines)}, символов {len(text):,} → {args.out}')
    print(f'окон при сборке (шаг 640, окно 800): ~{(len(text) - 800) // 640 + 1:,}')


if __name__ == '__main__':
    main()
